test("K1 · 口语用例集：意图识别（142 条真实说法）", () => {
  let failed = 0;
  const misses = [];
  for (const [utt, want] of SPOKEN){
    const got = cat(utt);
    if (got !== want){ failed++; misses.push(`「${utt}」 期望 ${want}，实际 ${got}`); }
  }
  assert.equal(failed, 0, `\n${misses.length}/${SPOKEN.length} 条口语用例未命中：\n` + misses.join("\n"));
});

test("K1 · 口语用例集：关键槽位抽取（物品 / 数量 / 目的地 / 动作）", () => {
  const failed = [];
  for (const [utt, want, wantArgs] of SPOKEN){
    if (!wantArgs) continue;
    const got = argsOf(utt);
    for (const [k, v] of Object.entries(wantArgs)){
      if (got[k] !== v) failed.push(`「${utt}」 参数 ${k} 期望 ${v}，实际 ${got[k]}`);
    }
  }
  assert.equal(failed.length, 0, `\n${failed.length} 条槽位断言未通过：\n` + failed.join("\n"));
});

test("K1 · 引擎硬约束：args 必须是数组（send() 走 Array.isArray 分支）", () => {
  for (const [utt] of SPOKEN){
    const r = E.parse(utt);
    assert.ok(Array.isArray(r[0].args), `「${utt}」的 args 必须是数组`);
    assert.ok(typeof r[0].args[0] === "object", `「${utt}」的 args[0] 必须是对象`);
  }
});

test("K1 · 引擎硬约束：接不住时不硬猜（低分落到「其他意图」）", () => {
  for (const junk of ["asdfghjkl", "……", "嗯", "？", "，，，"]){
    assert.equal(cat(junk), "其他意图", `「${junk}」不该被硬猜成具体意图`);
  }
});

