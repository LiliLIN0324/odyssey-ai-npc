// ============================================================
// 奥德赛 · 离线意图引擎门禁（批次 K1）
// ============================================================
//  为什么有这套测试：真实协议入口的 key 一旦失效（HTTP 401），
//  玩家说的每一句话都会落到离线意图引擎——**离线引擎的水平就是
//  玩家实际体验到的对话理解水平**。所以它必须有可回归的数字。
//
//  三个断言组：
//   ① 口语用例集（170 条）：玩家真会说的话（口语、缩写、错字、
//      省略、连说两件事），逐条断言意图与关键槽位；
//   ② 旧表差分：旧 localFallbackParse 支持的 22 个意图，新引擎
//      必须一个不落地覆盖（不许因为重写而功能倒退）；
//   ③ 引擎硬约束：args 必须是数组；低分不硬猜；数量/物品抽取正确。
// ============================================================
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const ROOT = path.resolve(__dirname, "..");
const source = (file) => fs.readFileSync(path.join(ROOT, file), "utf8");

function makeEngine(){
  const ctx = vm.createContext({ console, window: {} });
  vm.runInContext(source("src/agent/localIntent.js"), ctx, { filename: "localIntent.js" });
  return ctx.window.LOCAL_INTENT;
}

const E = makeEngine();

/** 解析并返回第一条意图的 category */
function cat(text){
  const r = E.parse(text);
  assert.ok(Array.isArray(r) && r.length, `「${text}」应解析出至少一个意图`);
  return r[0].category;
}
/** 解析并返回第一条意图的第一个参数对象 */
function argsOf(text){
  const r = E.parse(text);
  assert.ok(Array.isArray(r) && r.length, `「${text}」应解析出至少一个意图`);
  return (r[0].args && r[0].args[0]) || {};
}

