/* 上游 API 偶发 403/429/5xx（实测部署版间歇性失败）→ 半秒退避重试一次；
   400/参数错不重试（重试也没用）。网络异常同样重试一次。 */
async function postJSON(url, payload, timeoutMs){
  /* 超时兜底：弱网下「正在思索…」不能悬 10s+（parse 8s / chat 15s；超时不重试直接走本地降级） */
  const tryOnce = async () => {
    const ac = (typeof AbortController!=="undefined") ? new AbortController() : null;
    const tid = ac ? setTimeout(()=>ac.abort(), timeoutMs||0) : null;
    let r;
    try {
      r = await fetch(url, {method:"POST", headers:{"Content-Type":"application/json"}, body:JSON.stringify(payload), signal: ac ? ac.signal : undefined});
    } catch(err){
      if (err && err.name==="AbortError"){ const e = new Error("请求超时"); e.noRetry = true; throw e; }
      throw err;
    } finally { if (tid) clearTimeout(tid); }
    const d = await r.json().catch(()=>({error:"响应异常"}));
    /* 服务端已经把上游重试耗尽了（upstreamExhausted）→ 客户端别再重试：
       否则同一句话要连打三轮上游，纯烧额度还把玩家等烦。
       额度用尽（429）同理——那是确定性的拒绝，重试多少次都是 429。 */
    if (d && d.upstreamExhausted){
      const err=new Error(d.error || "上游暂不可用");
      err.status=r.status; err.noRetry=true; throw err;
    }
    if (r.status===429){
      const err=new Error(d.error || "今日额度已用完");
      err.status=429; err.noRetry=true; throw err;
    }
    if (!r.ok || d.error || d.content===undefined){
      const err = new Error(d.error || ("HTTP "+r.status));
      err.status = r.status;
      throw err;
    }
    return d;
  };
  try { return await tryOnce(); }
  catch(e){
    if (e.noRetry) throw e;
    const s = e.status || 0;
    /* 403 常成簇出现：两层退避（短+长）比单次重试更能逃出限流窗口（实测压测后升级）。
       405 也重试：2026-11-15 线上偶发过一次「POST /api/parse → 405」且**无法复现**
       （同一秒后续请求正常，疑似边缘节点瞬时行为）——重试一次成本极低，值得兜住。 */
    if (s===403 || s===405 || s===429 || (s>=500 && s<600) || s===0){
      for (const delay of [600, 2500]){
        await new Promise(res=>setTimeout(res, delay + Math.random()*300));
        try { return await tryOnce(); } catch(e2){ if (!(e2.status===403 || e2.status===405 || e2.status===429 || (e2.status>=500 && e2.status<600) || e2.status===0)) throw e2; }
      }
    }
    throw e;
  }
}
